-- +goose Up
-- groups gather accounts that are one place to the user, like every wise
-- currency balance. they only shape how accounts are shown and filtered
CREATE TABLE account_groups (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id    UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name        TEXT        NOT NULL,
  color       TEXT        NOT NULL DEFAULT '#3b82f6' CHECK (color ~ '^#[0-9a-fA-F]{6}$'),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT account_groups_owner_name_unique UNIQUE (owner_id, name)
);

CREATE TRIGGER trg_account_groups_update
  BEFORE UPDATE ON account_groups
  FOR EACH ROW EXECUTE FUNCTION touch_updated_at();

ALTER TABLE accounts
  ADD COLUMN group_id BIGINT REFERENCES account_groups(id) ON DELETE SET NULL;

CREATE INDEX idx_accounts_group ON accounts(group_id) WHERE group_id IS NOT NULL;

